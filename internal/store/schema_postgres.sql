-- Action rows are append-only (#682): every UPDATE is refused except the
-- retention prompt scrub (ADR 0081), matching SQLite's actions_append_only.
CREATE FUNCTION actions_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  allowed boolean;
BEGIN
  -- An IF condition ends at its first THEN, so the CASE is assigned first.
  allowed := NEW.action_id IS NOT DISTINCT FROM OLD.action_id
    AND NEW.session_id IS NOT DISTINCT FROM OLD.session_id
    AND NEW.turn_id IS NOT DISTINCT FROM OLD.turn_id
    AND NEW.review_revision_id IS NOT DISTINCT FROM OLD.review_revision_id
    AND NEW.repo IS NOT DISTINCT FROM OLD.repo
    AND NEW.item IS NOT DISTINCT FROM OLD.item
    AND NEW.action_type IS NOT DISTINCT FROM OLD.action_type
    AND NEW.reason_code IS NOT DISTINCT FROM OLD.reason_code
    AND NEW.evidence_class IS NOT DISTINCT FROM OLD.evidence_class
    AND NEW.limit_sentence IS NOT DISTINCT FROM OLD.limit_sentence
    AND CASE OLD.action_type
      WHEN 'operator.steer' THEN
        CASE WHEN json_valid(OLD.body)
          THEN NEW.body IS NOT DISTINCT FROM json_set(OLD.body, '$.prompt', '')
          ELSE NEW.body IS NOT DISTINCT FROM '{"prompt":""}' END
      WHEN 'acp.session.update' THEN
        CASE WHEN NOT json_valid(OLD.body) THEN false
          WHEN jsonb_typeof(OLD.body::jsonb #> '{update,content}') = 'object'
            THEN NEW.body IS NOT DISTINCT FROM json_set(OLD.body, '$.update.content.text', '')
          ELSE false END
      ELSE false END;
  IF allowed THEN
    RETURN NEW;
  END IF;
  RAISE EXCEPTION 'actions are append-only';
END $$;
CREATE TRIGGER actions_append_only BEFORE UPDATE ON actions
  FOR EACH ROW EXECUTE FUNCTION actions_append_only();
