-- PostgreSQL baseline: the SQLite schema at CurrentSchema, translated.
-- INTEGER PRIMARY KEY ids are identities, INTEGER is BIGINT, BLOB is BYTEA.
-- Boolean columns stay integer 0/1, as in SQLite. A migration that changes
-- the SQLite schema must change this file too (see the drift test).

-- unixepoch is SQLite's store clock: the transaction's epoch seconds (ADR 0089 D4).
CREATE FUNCTION unixepoch() RETURNS bigint LANGUAGE sql STABLE
  RETURN floor(extract(epoch FROM transaction_timestamp()))::bigint;

-- group_concat(value, separator) is SQLite's string aggregate, used by FollowToken.
CREATE FUNCTION group_concat_step(acc text, val text, sep text) RETURNS text LANGUAGE sql IMMUTABLE
  RETURN CASE WHEN val IS NULL THEN acc WHEN acc IS NULL THEN val ELSE acc || sep || val END;
CREATE AGGREGATE group_concat(text, text) (SFUNC = group_concat_step, STYPE = text);

-- json_extract(doc, path) is SQLite's JSON scalar read, used on stored payloads.
CREATE FUNCTION json_extract(doc text, path text) RETURNS text LANGUAGE sql IMMUTABLE
  RETURN jsonb_path_query_first(doc::jsonb, path::jsonpath) #>> '{}';

-- json_array_length(doc, path) is SQLite's JSON array length, used by the inbox.
CREATE FUNCTION json_array_length(doc text, path text) RETURNS bigint LANGUAGE sql IMMUTABLE
  RETURN (SELECT CASE WHEN v IS NULL THEN NULL WHEN jsonb_typeof(v) = 'array' THEN jsonb_array_length(v) ELSE 0 END
          FROM jsonb_path_query_first(doc::jsonb, path::jsonpath) AS v);

-- json_valid(doc) is SQLite's JSON check, used by the retention scrub.
CREATE FUNCTION json_valid(doc text) RETURNS boolean LANGUAGE plpgsql IMMUTABLE AS $$
BEGIN
  PERFORM doc::jsonb;
  RETURN doc IS NOT NULL;
EXCEPTION WHEN others THEN
  RETURN false;
END $$;

-- json_set(doc, path, value, ...) is SQLite's JSON write for '$.a.b' paths
-- and text values, used by the retention scrub and the append-only trigger.
CREATE FUNCTION json_set(doc text, VARIADIC kv text[]) RETURNS text LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE
  j jsonb := doc::jsonb;
BEGIN
  FOR i IN 1 .. coalesce(array_length(kv, 1), 0) - 1 BY 2 LOOP
    j := jsonb_set(j, string_to_array(substr(kv[i], 3), '.'), coalesce(to_jsonb(kv[i + 1]), 'null'::jsonb), true);
  END LOOP;
  RETURN j::text;
END $$;

